export interface DashboardStateFixture {
  readonly name: string;
  readonly purpose: string;
  readonly nowUnixMs: number;
  readonly overview: HealthOverview;
}

export interface FatalFixture {
  readonly name: string;
  readonly purpose: string;
  readonly error: OverviewError;
}

export interface DashboardFixtures {
  readonly states: readonly DashboardStateFixture[];
  readonly fatal: readonly FatalFixture[];
}

/** Generated by `rocm_app_core::health`'s test suite. */
export const FIXTURES = rawFixtures as unknown as DashboardFixtures;

export function fixtureState(name: string): DashboardStateFixture {
  const found = FIXTURES.states.find((s) => s.name === name);
  if (!found) {
    throw new Error(`unknown dashboard fixture: ${name}`);
  }
  return found;
}

/** A source that replays one generated state. */
export function fixtureSource(name: string): DashboardSource {
  const state = fixtureState(name);
  return { overview: () => Promise.resolve(state.overview) };
}

/**
 * A refusal as a rejection.
 *
 * An `Error` subclass rather than a bare object: everything that catches a
 * promise expects one, and the extra `code` still travels for branching.
 */
export class OverviewFailure extends Error implements OverviewError {
  readonly code: string;

  constructor(failure: OverviewError) {
    super(failure.message);
    this.name = "OverviewFailure";
    this.code = failure.code;
  }
}

/** A source that always refuses, for the fatal-error state. */
export function failingSource(error: OverviewError): DashboardSource {
  return { overview: () => Promise.reject(new OverviewFailure(error)) };
}
