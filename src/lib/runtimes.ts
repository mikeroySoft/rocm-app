export interface AuditRecord {
  readonly atUnixMs: number;
  readonly operation: string;
  readonly planId: string;
  readonly outcome: "started" | "completed" | "cancelled" | "failed";
  readonly errorCode: string | null;
}

export interface RuntimesStateFixture {
  readonly name: string;
  readonly purpose: string;
  readonly view: RuntimesView;
}

export interface OutcomeFixture {
  readonly name: string;
  readonly events: readonly ProgressEvent[];
}

export interface RuntimesFixtures {
  readonly states: readonly RuntimesStateFixture[];
  /** The activation plan the review screen renders, from the real controller. */
  readonly plan: ChangePlan;
  readonly outcomes: readonly OutcomeFixture[];
  readonly audit: readonly AuditRecord[];
}

/** Generated by `rocm_app_core::runtimes`' test suite. */
export const FIXTURES = rawFixtures as unknown as RuntimesFixtures;

export function fixtureState(name: string): RuntimesStateFixture {
  const found = FIXTURES.states.find((s) => s.name === name);
  if (!found) {
    throw new Error(`unknown runtimes fixture: ${name}`);
  }
  return found;
}

/** Records what the screen asked the backend to do. */
export interface RuntimesCalls {
  readonly plans: OperationRequest[];
  readonly executions: Approval[];
}

export interface FixtureRuntimes extends RuntimesBackend {
  readonly calls: RuntimesCalls;
}

/**
 * A backend that replays a generated state.
 *
 * `plan` refuses by default, because the states these fixtures describe are
 * mostly ones where planning *should* be refused; a test that wants the happy
 * path passes a plan in explicitly.
 */
export function fixtureOutcome(name: string): readonly ProgressEvent[] {
  const found = FIXTURES.outcomes.find((o) => o.name === name);
  if (!found) {
    throw new Error(`unknown runtimes outcome fixture: ${name}`);
  }
  return found.events;
}

export function fixtureRuntimes(
  name: string,
  options: { readonly plan?: ChangePlan; readonly events?: readonly ProgressEvent[] } = {},
): FixtureRuntimes {
  const state = fixtureState(name);
  const calls: RuntimesCalls = { plans: [], executions: [] };
  return {
    calls,
    view: () => Promise.resolve(state.view),
    plan: (request) => {
      calls.plans.push(request);
      return options.plan
        ? Promise.resolve(options.plan)
        : Promise.reject(new Error("this fixture has no plan"));
    },
    execute: (approval, onEvent) => {
      calls.executions.push(approval);
      for (const event of options.events ?? []) {
        onEvent(event);
      }
      return Promise.resolve();
    },
    cancel: () => Promise.resolve(),
  };
}
